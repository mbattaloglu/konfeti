/**
 * 3D Flip Axis.
 * - `"x"` — paper tumbles forward/backward (height squashes). The classic confetti look.
 * - `"y"` — paper turns left/right (width squashes).
 * - `"both"` — tumbles on both axes at slightly different speeds, for a chaotic flutter.
 */
export type FlipAxis = "x" | "y" | "both";
